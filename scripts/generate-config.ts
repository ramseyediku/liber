#!/usr/bin/env node
// Turns .env (gitignored — a browser extension has no process.env) into
// src/shared/env.ts, a plain module the extension's own code imports
// directly. Run via `npm run config` after editing .env.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(rootDir, ".env");
const outPath = join(rootDir, "src", "shared", "env.ts");

const REQUIRED_KEYS = ["SUPABASE_URL", "SUPABASE_ANON_KEY"] as const;

function parseEnvFile(text: string): Record<string, string> {
  const values: Record<string, string> = {};
  for (const rawLine of text.split("\n")) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

if (!existsSync(envPath)) {
  console.error(`Missing ${envPath} — copy .env.example to .env and fill it in first.`);
  process.exit(1);
}

const values = parseEnvFile(readFileSync(envPath, "utf8"));

const missing = REQUIRED_KEYS.filter((key) => !values[key]);
if (missing.length) {
  console.error(`Missing value(s) in .env: ${missing.join(", ")}`);
  process.exit(1);
}

const banner =
  "// Generated by scripts/generate-config.ts from .env — do not edit by hand,\n" +
  "// and do not commit this file (see .gitignore). Re-run `npm run config`\n" +
  "// after changing .env.\n";

const body = REQUIRED_KEYS.map((key) => `export const ${key} = ${JSON.stringify(values[key])};`).join(
  "\n",
);

writeFileSync(outPath, `${banner}\n${body}\n`);
console.log(`Wrote ${outPath}`);
